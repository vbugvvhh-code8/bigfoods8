-- Centrally stored food and drink names power the menu editor's type-ahead suggestions.
CREATE TABLE IF NOT EXISTS public.menu_catalog_item_names (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  category_name text NOT NULL,
  subcategory_name text NOT NULL,
  item_name text NOT NULL CHECK (length(btrim(item_name)) > 0),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS menu_catalog_item_names_unique_name_idx
  ON public.menu_catalog_item_names (lower(btrim(category_name)), lower(btrim(subcategory_name)), lower(btrim(item_name)));

ALTER TABLE public.menu_catalog_item_names ENABLE ROW LEVEL SECURITY;
GRANT SELECT ON public.menu_catalog_item_names TO authenticated;
DROP POLICY IF EXISTS "Authenticated users can read menu item name suggestions" ON public.menu_catalog_item_names;
CREATE POLICY "Authenticated users can read menu item name suggestions"
  ON public.menu_catalog_item_names FOR SELECT TO authenticated USING (true);

